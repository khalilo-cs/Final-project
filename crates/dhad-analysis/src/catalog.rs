pub fn builtin(name: &str) -> Option<&'static Item> {
    BUILTINS.iter().find(|i| i.name == name)
}

pub fn keyword(name: &str) -> Option<&'static Item> {
    KEYWORDS.iter().find(|i| i.name == name)
}

pub fn module(name: &str) -> Option<&'static (&'static str, &'static str, &'static [Item])> {
    MODULES.iter().find(|m| m.0 == name)
}

/// عضو وحدة، مع تجاهل التشكيل في الاسم (كما يفعل المحلل).
pub fn module_member(module_name: &str, member: &str) -> Option<&'static Item> {
    let strip = dhad_syntax::unicode::strip_tashkeel;
    module(module_name).and_then(|m| m.2.iter().find(|i| strip(i.name) == strip(member)))
}
