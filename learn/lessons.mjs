const EASTERN = "٠١٢٣٤٥٦٧٨٩";
export function normalizeOutput(s) {
  return s
    .replace(/[٠-٩]/g, (d) => String(EASTERN.indexOf(d)))
    .split("\n")
    .map((l) => l.trimEnd())
    .join("\n")
    .trim();
}

/** يبني البرنامج الذي يُصحَّح: كود الطالب + الاختبارات المخفية. */
export function gradedSource(lesson, code) {
  return lesson.check.tests ? `${code}\n\n# — اختبارات التصحيح —\n${lesson.check.tests}\n` : code;
}

/** يحكم على نتيجة تشغيل (كما يعيدها dhad_run) لدرس معيّن. */
export function judge(lesson, result) {
  if (result.error) return { passed: false, reason: "error" };
  if (lesson.check.output !== undefined) {
    const got = normalizeOutput(result.output || "");
    const want = normalizeOutput(lesson.check.output);
    return got === want ? { passed: true } : { passed: false, reason: "output", got, want };
  }
  return result.ok ? { passed: true } : { passed: false, reason: "tests" };
}
